#!/usr/bin/env python3
"""Writes the PS2 BIOS fetch + fastfetch configs from the shared clock art.

  fetch/build.py            write ~/.config/fetch/{config,logo.txt}
                            and ~/.config/fastfetch/ps2bios/{config.jsonc,logo.txt}
  fetch/build.py --activate also point ~/.config/fastfetch/config.jsonc at it
                            (the previous one is kept as config.jsonc.bak-ps2bios)

Palette matches theme/ps2Bios/theme.json and the clock shader.
"""
import json
import os
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import clock_ascii  # noqa: E402

HOME = Path.home()
CFG = Path(os.environ.get("XDG_CONFIG_HOME", HOME / ".config"))

PRISM_A = (90, 108, 240)     # #5a6cf0 periwinkle
PRISM_B = (73, 216, 196)     # #49d8c4 teal
ORB = (191, 244, 255)        # #bff4ff ice
RING = (125, 128, 179)       # #7d80b3 outline
TEXT = (228, 230, 251)       # #e4e6fb
DIM = (58, 58, 107)          # #3a3a6b
FACE = (169, 180, 255)       # #a9b4ff lit crystal face
SIDE = (74, 86, 214)         # #4a56d6 prism side in shadow


def hexc(rgb):
    return "#%02x%02x%02x" % rgb


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print("wrote", path)


# ---------------------------------------------------------------- fetch (3D)
def build_fetch():
    logo = "\n".join(clock_ascii.plain()) + "\n"
    write(CFG / "fetch" / "logo.txt", logo)
    config = f"""# PS2 BIOS look (generated by ~/ps2-dms-niri/fetch/build.py; edit that, not this)
os
host
kernel
uptime
packages
shell
---
wm
terminal
cpu
gpu
memory
disk

# label colour: 256-colour periwinkle (truecolour doesn't fit fetch's 15-char limit)
label_color=38;5;111
separator=─
show_title=1
box=0

# crystal faces in light periwinkle, extruded sides in deep prism blue
logo_inner=38;2;{FACE[0]};{FACE[1]};{FACE[2]}
logo_outer=38;2;{SIDE[0]};{SIDE[1]};{SIDE[2]}

# a slow turn on one axis, like the prisms on the clock
spin=y
speed=0.6
light=top-left
shading_mode=sextants
"""
    write(CFG / "fetch" / "config", config)


# ---------------------------------------------------------------- fastfetch
def build_fastfetch(activate):
    import math
    grid = clock_ascii.cells()
    h, w = len(grid), len(grid[0])
    cx, cy = (w - 1) / 2, (h - 1) / 2
    lines = []
    for y, row in enumerate(grid):
        out, cur = [], None
        for x, role in enumerate(row):
            r = math.hypot((x - cx) / clock_ascii.ASPECT, y - cy)
            if role in "pe":
                # periwinkle at the inner end, teal at the tip, like the shader's prisms
                band = 0 if r < 7.2 else (1 if r < 8.8 else 2)
                code, ch = ("1", "5", "6")[band], ("█" if role == "p" else "▓")
                if role == "e":
                    code = ("2", "2", "7")[band]
            elif role == "o":
                code, ch = "4", "●"
            elif role == "r":
                code, ch = "3", "·"
            else:
                code, ch = None, " "
            if code and code != cur:
                out.append("$" + code)
                cur = code
            out.append(ch)
        lines.append("".join(out).rstrip())
    write(CFG / "fastfetch" / "ps2bios" / "logo.txt", "\n".join(lines) + "\n")

    def mix(a, b, t):
        return tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))

    colors = {
        "1": hexc(PRISM_A),                       # prism core, inner
        "2": hexc(mix(PRISM_A, (13, 11, 38), 0.35)),  # prism edge
        "3": hexc(RING),                          # orb ring
        "4": hexc(ORB),                           # orbs
        "5": hexc(mix(PRISM_A, PRISM_B, 0.5)),    # prism core, middle
        "6": hexc(PRISM_B),                       # prism core, tip
        "7": hexc(mix(PRISM_B, (13, 11, 38), 0.35)),  # tip edge
    }
    key = "#8f9cff"
    spaced = "  ".join("s y s t e m   c o n f i g u r a t i o n".split("   "))

    def mod(t, k, **extra):
        return {"type": t, "key": k, **extra}

    def dot(rgb):
        return "{#38;2;%d;%d;%d}●" % rgb

    config = {
        "$schema": "https://github.com/fastfetch-cli/fastfetch/raw/dev/doc/json_schema.json",
        "logo": {
            "type": "file",
            "source": str(CFG / "fastfetch" / "ps2bios" / "logo.txt"),
            "color": colors,
            "padding": {"top": 1, "left": 1, "right": 4},
        },
        "display": {
            "separator": "  ",
            "brightColor": False,
            "color": {"keys": key, "title": hexc(ORB), "output": hexc(TEXT), "separator": hexc(RING)},
            "bar": {
                "char": {"elapsed": "━", "total": "─"},
                "width": 10,
                "color": {"elapsed": hexc(PRISM_B), "total": hexc(DIM)},
            },
            "percent": {
                "type": 10,
                "color": {"green": hexc(PRISM_B), "yellow": "#ffd27a", "red": "#ff7a93"},
            },
        },
        "modules": [
            {"type": "custom", "format": "{#38;2;%d;%d;%d}%s{#}" % (ORB + (spaced,))},
            {"type": "custom", "format": "{#38;2;%d;%d;%d}%s{#}" % (DIM + ("─" * len(spaced),))},
            mod("title", "  ", format="{user-name}{#38;2;%d;%d;%d}@{#}{host-name}" % RING),
            mod("os", "  os"),
            mod("kernel", "  kernel"),
            mod("uptime", "  uptime"),
            mod("shell", "  shell"),
            "break",
            mod("wm", "  wm"),
            mod("terminal", "  terminal"),
            mod("cpu", "  cpu", showPeCoreCount=False),
            mod("gpu", "  gpu"),
            mod("memory", "  memory"),
            mod("disk", "  disk", folders="/"),
            "break",
            {"type": "custom", "format": "   " + " ".join(dot(c) for c in
                (PRISM_A, mix(PRISM_A, PRISM_B, 0.5), PRISM_B, ORB, (143, 156, 255), RING)) + "{#}"},
        ],
    }
    write(CFG / "fastfetch" / "ps2bios" / "config.jsonc",
          "// PS2 BIOS look, generated by ~/ps2-dms-niri/fetch/build.py (edit that, not this)\n"
          + json.dumps(config, indent=2, ensure_ascii=False) + "\n")

    if activate:
        active = CFG / "fastfetch" / "config.jsonc"
        backup = active.with_name("config.jsonc.bak-ps2bios")
        if active.exists() and not backup.exists():
            shutil.copy2(active, backup)
            print("backed up", active, "->", backup)
        shutil.copy2(CFG / "fastfetch" / "ps2bios" / "config.jsonc", active)
        print("activated", active)


if __name__ == "__main__":
    build_fetch()
    build_fastfetch("--activate" in sys.argv)
